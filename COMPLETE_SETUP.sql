create or replace function public.create_profile_for_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
begin
    insert into public.profiles (id, email, full_name, phone)
    values (
        new.id,
        lower(new.email),
        coalesce(new.raw_user_meta_data ->> 'full_name', ''),
        nullif(new.raw_user_meta_data ->> 'phone', '')
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.create_profile_for_auth_user();

create or replace function public.prevent_profile_role_escalation()
returns trigger
language plpgsql
set search_path = public
as $$
begin
    if auth.uid() = old.id and new.role is distinct from old.role then
        raise exception 'Profile roles cannot be changed by the account owner.';
    end if;
    return new;
end;
$$;

drop trigger if exists protect_profile_role on public.profiles;
create trigger protect_profile_role
    before update on public.profiles
    for each row execute function public.prevent_profile_role_escalation();

-- Preserve removed menu/poster records: hide them instead of deleting history.
create or replace function public.replace_menu_items(p_items jsonb)
returns void
language plpgsql
set search_path = public
as $$
begin
    if auth.role() <> 'service_role' or jsonb_typeof(p_items) <> 'array' then
        raise exception 'Not authorized or menu payload is invalid.';
    end if;

    update public.menu_items existing
    set is_available = false,
        updated_at = now()
    where not exists (
        select 1
        from jsonb_to_recordset(p_items) as incoming(id bigint)
        where incoming.id = existing.id
    );

    insert into public.menu_items (id, name, category, price, image_url, description)
    select id, name, category, price, image, coalesce(description, '')
    from jsonb_to_recordset(p_items) as incoming(
        id bigint,
        name text,
        category text,
        price numeric,
        image text,
        description text
    )
    on conflict (id) do update set
        name = excluded.name,
        category = excluded.category,
        price = excluded.price,
        image_url = excluded.image_url,
        description = excluded.description,
        is_available = true,
        updated_at = now();

    if exists (select 1 from public.menu_items) then
        perform setval(
            pg_get_serial_sequence('public.menu_items', 'id'),
            (select max(id) from public.menu_items),
            true
        );
    end if;
end;
$$;

create or replace function public.replace_posters(p_posters jsonb)
returns void
language plpgsql
set search_path = public
as $$
begin
    if auth.role() <> 'service_role' or jsonb_typeof(p_posters) <> 'array' then
        raise exception 'Not authorized or poster payload is invalid.';
    end if;

    update public.posters existing
    set is_published = false
    where not exists (
        select 1
        from jsonb_to_recordset(p_posters) as incoming(id bigint)
        where incoming.id = existing.id
    );

    insert into public.posters (
        id, title, description, category, image_url, is_published,
        expires_at, button_label, button_url
    )
    select
        id, title, coalesce(description, ''), coalesce(category, ''),
        image, coalesce(is_published, true), expires_at,
        coalesce(button_label, ''), coalesce(button_url, '')
    from jsonb_to_recordset(p_posters) as incoming(
        id bigint,
        title text,
        description text,
        category text,
        image text,
        is_published boolean,
        expires_at date,
        button_label text,
        button_url text
    )
    on conflict (id) do update set
        title = excluded.title,
        description = excluded.description,
        category = excluded.category,
        image_url = excluded.image_url,
        is_published = excluded.is_published,
        expires_at = excluded.expires_at,
        button_label = excluded.button_label,
        button_url = excluded.button_url;

    if exists (select 1 from public.posters) then
        perform setval(
            pg_get_serial_sequence('public.posters', 'id'),
            (select max(id) from public.posters),
            true
        );
    end if;
end;
$$;

