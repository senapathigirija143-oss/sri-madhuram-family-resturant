drop policy if exists "Customers can read their own profile" on public.profiles;
create policy "Customers can read their own profile"
    on public.profiles for select to authenticated
    using ((select auth.uid()) = id);

drop policy if exists "Public can read available menu items" on public.menu_items;
create policy "Public can read available menu items"
    on public.menu_items for select to anon, authenticated
    using (is_available);

drop policy if exists "Public can read published posters" on public.posters;
create policy "Public can read published posters"
    on public.posters for select to anon, authenticated
    using (is_published and (expires_at is null or expires_at >= current_date));

drop policy if exists "Public can read restaurant settings" on public.restaurant_settings;
create policy "Public can read restaurant settings"
    on public.restaurant_settings for select to anon, authenticated
    using (id = 'default');

drop policy if exists "Customers can read their own orders" on public.orders;
create policy "Customers can read their own orders"
    on public.orders for select to authenticated
    using ((select auth.uid()) = user_id);

drop policy if exists "Customers can read their own order items" on public.order_items;
create policy "Customers can read their own order items"
    on public.order_items for select to authenticated
    using (
        exists (
            select 1
            from public.orders
            where orders.id = order_items.order_id
              and orders.user_id = (select auth.uid())
        )
    );

