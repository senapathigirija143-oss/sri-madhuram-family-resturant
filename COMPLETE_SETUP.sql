    end if;

    if not exists (
        select 1 from pg_constraint
        where conrelid = 'public.orders'::regclass
          and conname = 'orders_refund_status_valid'
    ) then
        alter table public.orders
            add constraint orders_refund_status_valid check (
                refund_status in (
                    'not_requested', 'not_required', 'admin_requested',
                    'processing', 'processed', 'failed'
                )
            );
    end if;

    if not exists (
        select 1 from pg_constraint
        where conrelid = 'public.orders'::regclass
          and conname = 'orders_processed_refund_has_gateway_id'
    ) then
        alter table public.orders
            add constraint orders_processed_refund_has_gateway_id check (
                refund_status <> 'processed' or razorpay_refund_id is not null
            );
    end if;

    if not exists (
        select 1 from pg_constraint
        where conrelid = 'public.orders'::regclass
          and conname = 'orders_cancellation_details_valid'
    ) then
        alter table public.orders
            add constraint orders_cancellation_details_valid check (
                (
                    status <> 'Cancelled'
                    and cancelled_at is null
                    and cancellation_reason is null
                    and cancellation_policy is null
                    and food_making_deduction is null
                    and delivery_deduction is null
                    and refund_amount is null
                )
                or (
                    status = 'Cancelled'
                    and cancelled_at is not null
                    and cancellation_reason is not null
                    and cancellation_policy is not null
                    and cancellation_policy in (
                        'restaurant_stage_full_refund',
                        'delivery_stage_deductions'
                    )
                    and food_making_deduction is not null
                    and food_making_deduction >= 0
                    and delivery_deduction is not null
                    and delivery_deduction >= 0
                    and refund_amount is not null
                    and refund_amount >= 0
                )
            );
    end if;
end;
