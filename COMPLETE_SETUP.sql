-- Sri Madhuram Family Restaurant: consolidated Supabase schema and policies.
-- Safe to run on a new Supabase project or over the repository's existing schema.
-- This script does not read secrets, delete application rows, or contact a live service.
--
-- Categories follow the current application model: menu_items.category and
-- posters.category are text fields. There is no separate category CRUD surface.

begin;

create table if not exists public.profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    email text not null unique,
    full_name text not null default '',
    phone text unique,
    role text not null default 'customer'
        check (role in ('customer', 'admin')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.menu_items (
    id bigint generated by default as identity primary key,
    name text not null,
    category text not null,
    price numeric(10, 2) not null check (price > 0),
    image_url text not null,
    description text not null default '',
    is_available boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.posters (
    id bigint generated by default as identity primary key,
    title text not null,
    description text not null default '',
    category text not null default '',
    image_url text not null,
    is_published boolean not null default true,
    expires_at date,
    button_label text not null default '',
    button_url text not null default '',
    created_at timestamptz not null default now()
);

create table if not exists public.restaurant_settings (
    id text primary key default 'default',
    restaurant_name text not null,
    phone text not null default '',
    email text not null default '',
    address text not null default '',
    opening_hours text not null default '',
    delivery_fee numeric(10, 2) not null default 30
        check (delivery_fee >= 0),
    tax_rate numeric(5, 4) not null default 0.05
        check (tax_rate >= 0 and tax_rate <= 1),
    updated_at timestamptz not null default now()
);

create table if not exists public.orders (
    id text primary key,
    user_id uuid references public.profiles (id) on delete set null,
    name text not null,
    phone text not null,
    order_type text not null default 'Delivery',
    total numeric(10, 2) not null check (total > 0),
    payment_method text not null check (payment_method in ('upi', 'cod')),
    status text not null default 'Pending'
        check (status in (
            'Pending', 'Approved', 'Cooking', 'Out for Delivery',
            'Delivered', 'Cancelled'
        )),
    address text not null,
    created_at timestamptz not null default now(),
    legacy_data jsonb,
    location_latitude double precision,
    location_longitude double precision,
    location_accuracy_m double precision,
    location_captured_at timestamptz,
    food_subtotal numeric(10, 2),
    delivery_charge numeric(10, 2),
    payment_status text not null default 'unverified'
        check (payment_status in ('unverified', 'unpaid', 'paid')),
    paid_amount numeric(10, 2) not null default 0
        check (paid_amount >= 0),
    razorpay_order_id text,
    razorpay_payment_id text,
    cancelled_at timestamptz,
    cancellation_reason text,
    cancellation_policy text,
    food_making_deduction numeric(10, 2),
    delivery_deduction numeric(10, 2),
    refund_amount numeric(10, 2),
    refund_status text not null default 'not_requested'
        check (refund_status in (
            'not_requested', 'not_required', 'admin_requested',
            'processing', 'processed', 'failed'
        )),
    razorpay_refund_id text
);

create table if not exists public.order_items (
    id bigint generated by default as identity primary key,
    order_id text not null references public.orders (id) on delete cascade,
    menu_item_id bigint references public.menu_items (id) on delete set null,
    item_name text not null,
    quantity integer not null check (quantity between 1 and 100),
    unit_price numeric(10, 2) not null check (unit_price > 0),
    unique (order_id, item_name)
);

