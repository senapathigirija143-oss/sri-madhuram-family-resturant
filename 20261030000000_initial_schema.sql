create table if not exists public.profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    email text not null unique,
    full_name text not null default '',
    phone text unique,
    role text not null default 'customer' check (role in ('customer', 'admin')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.menu_items (
    id bigint generated by default as identity primary key,
    name text not null,
    category text not null,
    price numeric(10, 2) not null check (price > 0),
    image_url text not null,
    description text not null default '',
    is_available boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.posters (
    id bigint generated by default as identity primary key,
    title text not null,
    description text not null default '',
    category text not null default '',
    image_url text not null,
    is_published boolean not null default true,
    expires_at date,
    button_label text not null default '',
    button_url text not null default '',
    created_at timestamptz not null default now()
);

create table if not exists public.restaurant_settings (
    id text primary key default 'default',
    restaurant_name text not null,
    phone text not null default '',
    email text not null default '',
    address text not null default '',
    opening_hours text not null default '',
    delivery_fee numeric(10, 2) not null default 30 check (delivery_fee >= 0),
    tax_rate numeric(5, 4) not null default 0.05 check (tax_rate >= 0 and tax_rate <= 1),
    updated_at timestamptz not null default now()
);

create table if not exists public.orders (
    id text primary key,
    user_id uuid references public.profiles (id) on delete set null,
    name text not null,
    phone text not null,
    order_type text not null default 'Delivery',
    total numeric(10, 2) not null check (total > 0),
    payment_method text not null check (payment_method in ('upi', 'cod')),
    status text not null default 'Pending'
        check (status in ('Pending', 'Approved', 'Cooking', 'Out for Delivery', 'Delivered')),
    address text not null,
    created_at timestamptz not null default now(),
    legacy_data jsonb
);

create table if not exists public.order_items (
    id bigint generated by default as identity primary key,
    order_id text not null references public.orders (id) on delete cascade,
    menu_item_id bigint references public.menu_items (id) on delete set null,
    item_name text not null,
    quantity integer not null check (quantity between 1 and 100),
    unit_price numeric(10, 2) not null check (unit_price > 0),
    unique (order_id, item_name)
);

create index if not exists orders_user_id_created_at_idx
    on public.orders (user_id, created_at desc);
create index if not exists order_items_order_id_idx
    on public.order_items (order_id);

create or replace function public.create_profile_for_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
begin
    insert into public.profiles (id, email, full_name, phone)
    values (
        new.id,
        lower(new.email),
        coalesce(new.raw_user_meta_data ->> 'full_name', ''),
        nullif(new.raw_user_meta_data ->> 'phone', '')
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.create_profile_for_auth_user();

create or replace function public.prevent_profile_role_escalation()
returns trigger
language plpgsql
set search_path = public
as $$
begin
    if auth.uid() = old.id and new.role is distinct from old.role then
        raise exception 'Profile roles cannot be changed by the account owner.';
    end if;
    return new;
end;
$$;

drop trigger if exists protect_profile_role on public.profiles;
create trigger protect_profile_role
    before update on public.profiles
    for each row execute function public.prevent_profile_role_escalation();

create or replace function public.replace_menu_items(p_items jsonb)
returns void
language plpgsql
set search_path = public
as $$
begin
    if auth.role() <> 'service_role' or jsonb_typeof(p_items) <> 'array' then
        raise exception 'Not authorized or menu payload is invalid.';
    end if;

    delete from public.menu_items existing
    where not exists (
        select 1
        from jsonb_to_recordset(p_items) as incoming(id bigint)
        where incoming.id = existing.id
    );

    insert into public.menu_items (id, name, category, price, image_url, description)
    select id, name, category, price, image, coalesce(description, '')
    from jsonb_to_recordset(p_items) as incoming(
        id bigint,
        name text,
        category text,
        price numeric,
        image text,
        description text
    )
    on conflict (id) do update set
        name = excluded.name,
        category = excluded.category,
        price = excluded.price,
        image_url = excluded.image_url,
        description = excluded.description,
        is_available = true,
        updated_at = now();

    perform setval(
        pg_get_serial_sequence('public.menu_items', 'id'),
        greatest(coalesce((select max(id) from public.menu_items), 1), 1),
        true
    );
end;
$$;

create or replace function public.replace_posters(p_posters jsonb)
returns void
language plpgsql
set search_path = public
as $$
begin
    if auth.role() <> 'service_role' or jsonb_typeof(p_posters) <> 'array' then
        raise exception 'Not authorized or poster payload is invalid.';
    end if;

    delete from public.posters existing
    where not exists (
        select 1
        from jsonb_to_recordset(p_posters) as incoming(id bigint)
        where incoming.id = existing.id
    );

    insert into public.posters (
        id, title, description, category, image_url, is_published,
        expires_at, button_label, button_url
    )
    select
        id, title, coalesce(description, ''), coalesce(category, ''),
        image, coalesce(is_published, true), expires_at,
        coalesce(button_label, ''), coalesce(button_url, '')
    from jsonb_to_recordset(p_posters) as incoming(
        id bigint,
        title text,
        description text,
        category text,
        image text,
        is_published boolean,
        expires_at date,
        button_label text,
        button_url text
    )
    on conflict (id) do update set
        title = excluded.title,
        description = excluded.description,
        category = excluded.category,
        image_url = excluded.image_url,
        is_published = excluded.is_published,
        expires_at = excluded.expires_at,
        button_label = excluded.button_label,
        button_url = excluded.button_url;

    perform setval(
        pg_get_serial_sequence('public.posters', 'id'),
        greatest(coalesce((select max(id) from public.posters), 1), 1),
        true
    );
end;
$$;

create or replace function public.create_customer_order(
    p_user_id uuid,
    p_name text,
    p_phone text,
    p_address text,
    p_payment_method text,
    p_items jsonb
)
returns text
language plpgsql
set search_path = public
as $$
declare
    v_order_id text;
    v_subtotal numeric(10, 2);
    v_item_count integer;
    v_expected_count integer;
    v_tax_rate numeric(5, 4);
    v_delivery_fee numeric(10, 2);
begin
    if auth.role() <> 'service_role'
        or jsonb_typeof(p_items) <> 'array'
        or jsonb_array_length(p_items) = 0
        or p_payment_method not in ('upi', 'cod') then
        raise exception 'Not authorized or order details are invalid.';
    end if;

    select count(*), coalesce(sum(menu.price * incoming.quantity), 0)
    into v_item_count, v_subtotal
    from jsonb_to_recordset(p_items) as incoming(menu_item_id bigint, quantity integer)
    join public.menu_items menu
        on menu.id = incoming.menu_item_id and menu.is_available
    where incoming.quantity between 1 and 100;

    select count(*) into v_expected_count
    from jsonb_to_recordset(p_items) as incoming(menu_item_id bigint, quantity integer);

    if v_item_count <> v_expected_count or v_item_count = 0 then
        raise exception 'One or more order items are invalid or unavailable.';
    end if;

    select delivery_fee, tax_rate
    into v_delivery_fee, v_tax_rate
    from public.restaurant_settings
    where id = 'default';

    v_delivery_fee := coalesce(v_delivery_fee, 30);
    v_tax_rate := coalesce(v_tax_rate, 0.05);
    v_order_id := 'ORD-' || upper(replace(gen_random_uuid()::text, '-', ''));

    insert into public.orders (
        id, user_id, name, phone, total, payment_method, status, address
    )
    values (
        v_order_id,
        p_user_id,
        p_name,
        p_phone,
        round(v_subtotal * (1 + v_tax_rate) + v_delivery_fee),
        p_payment_method,
        'Pending',
        p_address
    );

    insert into public.order_items (order_id, menu_item_id, item_name, quantity, unit_price)
    select v_order_id, menu.id, menu.name, incoming.quantity, menu.price
    from jsonb_to_recordset(p_items) as incoming(menu_item_id bigint, quantity integer)
    join public.menu_items menu
        on menu.id = incoming.menu_item_id and menu.is_available;

    return v_order_id;
end;
$$;

